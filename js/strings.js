/** t('key', { name: 'value' }) -> text with {name} replaced. */
export function t(key, vars = {}) {
  const text = STRINGS[key];
  if (text === undefined) {
    console.warn(`Missing text for "${key}"`);
    return key;
  }
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
